const dictionaries: Record<Lang, Record<Key, Entry>> = { en, cs };

let current: Lang | null = null;

function detect(): Lang {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored === "en" || stored === "cs") return stored;
  } catch {
    // Storage unavailable: fall through to the browser's language.
  }
  const prefs = typeof navigator === "undefined" ? [] : (navigator.languages?.length ? navigator.languages : [navigator.language]);
  return prefs.some((l) => /^(cs|sk)\b/i.test(l ?? "")) ? "cs" : "en";
}

export function lang(): Lang {
  current ??= detect();
  return current;
}

export function setLang(l: Lang): void {
  current = l;
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    // Not persisted; still applies for this visit.
  }
  if (typeof document !== "undefined") document.documentElement.lang = l;
}

function render(dict: Record<Key, Entry>, key: Key, params: Params = {}): string {
  const entry = dict[key];
  if (typeof entry === "function") return entry(params);
  return entry.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function t(key: Key, params?: Params): string {
  return render(dictionaries[lang()], key, params);
}

/** English text whatever the language: for stable names (tests, ids), never for display. */
export function tEn(key: Key, params?: Params): string {
  return render(en, key, params);
}

/** "a, b and c" in the current language. */
export function joinList(items: string[]): string {
  if (items.length < 2) return items[0] ?? "";
  return t("listAnd", { head: items.slice(0, -1).join(", "), last: items[items.length - 1]! });
}
