import sys
# Draws the Koffbeat icon (a pixel dotted eighth note) from the grid below and writes
# public/favicon.svg, public/favicon-32.png, public/apple-touch-icon.png and the PWA sizes.
# Run: python3 scripts/make-icons.py  (needs Pillow)
from PIL import Image
# 16x16 pixel grid: a dotted eighth note. '#' = ink.
GRID = """
................
................
........##......
........###.....
........####....
........#.##....
........#..#....
........#..#....
........#.#.....
........#.......
.....####.......
....#####.......
....#####.##....
.....####.##....
................
................
""".strip("\n").splitlines()
assert all(len(r)==16 for r in GRID) and len(GRID)==16
INK="#1a1a1a"; PAPER="#ffffff"
cells=[(x,y) for y,r in enumerate(GRID) for x,c in enumerate(r) if c=="#"]
out=sys.argv[1] if len(sys.argv) > 1 else "public"
rects="".join(f'<rect x="{x}" y="{y}" width="1" height="1"/>' for x,y in cells)
open(f"{out}/favicon.svg","w").write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges"><rect width="16" height="16" rx="3" fill="{PAPER}"/><g fill="{INK}">{rects}</g></svg>\n')
def png(size, name):
    im=Image.new("RGB",(16,16),PAPER)
    for x,y in cells: im.putpixel((x,y),(0x1a,0x1a,0x1a))
    im.resize((size,size),Image.NEAREST).save(f"{out}/{name}")
for s,n in [(180,"apple-touch-icon.png"),(192,"icons/icon-192.png"),(512,"icons/icon-512.png"),(32,"favicon-32.png")]: png(s,n)
